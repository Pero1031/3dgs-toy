# -*- coding: utf-8 -*-
"""球面調和関数 (SH) による視点依存の色。

各ガウシアンは RGB ごとに (deg+1)^2 個の SH 係数を持ち、
視線方向 d（カメラ中心 → ガウシアン中心の単位ベクトル）に対して
    color(d) = Σ_lm k_lm Y_lm(d) + 0.5
とする。deg=0 なら方向によらない一定色（拡散色）になる。
定数と式は公式実装 (utils/sh_utils.py) と同じ実数 SH。
"""

C0 = 0.28209479177387814
C1 = 0.4886025119029199
C2 = (1.0925484305920792, -1.0925484305920792, 0.31539156525252005,
      -1.0925484305920792, 0.5462742152960396)
C3 = (-0.5900435899266435, 2.890611442640554, -0.4570457994644658, 0.3731763325901154,
      -0.4570457994644658, 1.445305721320277, -0.5900435899266435)


def eval_sh(deg, sh, dirs):
    """sh: (N, K, 3) [K >= (deg+1)^2],  dirs: (N, 3) 単位ベクトル  ->  (N, 3)"""
    out = C0 * sh[:, 0]
    if deg < 1:
        return out
    x, y, z = dirs[:, 0:1], dirs[:, 1:2], dirs[:, 2:3]
    out = out - C1 * y * sh[:, 1] + C1 * z * sh[:, 2] - C1 * x * sh[:, 3]
    if deg < 2:
        return out
    xx, yy, zz = x * x, y * y, z * z
    xy, yz, xz = x * y, y * z, x * z
    out = (out
           + C2[0] * xy * sh[:, 4]
           + C2[1] * yz * sh[:, 5]
           + C2[2] * (2 * zz - xx - yy) * sh[:, 6]
           + C2[3] * xz * sh[:, 7]
           + C2[4] * (xx - yy) * sh[:, 8])
    if deg < 3:
        return out
    out = (out
           + C3[0] * y * (3 * xx - yy) * sh[:, 9]
           + C3[1] * xy * z * sh[:, 10]
           + C3[2] * y * (4 * zz - xx - yy) * sh[:, 11]
           + C3[3] * z * (2 * zz - 3 * xx - 3 * yy) * sh[:, 12]
           + C3[4] * x * (4 * zz - xx - yy) * sh[:, 13]
           + C3[5] * z * (xx - yy) * sh[:, 14]
           + C3[6] * x * (xx - 3 * yy) * sh[:, 15])
    return out


def rgb_to_sh0(rgb):
    """一定色 rgb になる 0 次係数"""
    return (rgb - 0.5) / C0
